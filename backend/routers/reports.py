from datetime import date
import io

from fastapi import APIRouter, Depends, HTTPException, Response
from sqlalchemy.orm import Session

import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment

from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Table,
    TableStyle,
    Spacer,
    Flowable,
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

from database import models
from auth import get_db, get_current_user


router = APIRouter(tags=["Reports"])


# ==========================================
# GET REPORT STUDENTS
# ==========================================

def get_report_students(current_user, db):

    if current_user.role not in ["teacher", "principal"]:
        raise HTTPException(
            status_code=403,
            detail="Unauthorized role for report export",
        )

    if current_user.role == "teacher":
        return db.query(models.Student).filter(
            models.Student.teacher_id == current_user.id
        ).all()

    return db.query(models.Student).all()


# ==========================================
# EXPORT EXCEL
# ==========================================

@router.get("/reports/export/excel")
def export_excel(
    current_user=Depends(get_current_user),
    db: Session = Depends(get_db),
):

    students = get_report_students(current_user, db)

    wb = openpyxl.Workbook()

    # Create worksheet explicitly instead of using wb.active
    ws = wb.create_sheet("Attendance Report")

    # Title
    ws.merge_cells("A1:E1")
    ws["A1"] = "XYZ AI Assistant - Attendance Report"
    ws["A1"].font = Font(
        size=15,
        bold=True,
        color="FF7A00",
    )

    # Report information
    ws.merge_cells("A2:E2")
    ws["A2"] = (
        f"Generated by: {current_user.name} | "
        f"Date: {date.today().isoformat()}"
    )

    # Headers
    headers = [
        "Student ID",
        "Student Name",
        "Attendance %",
        "Standing",
        "Assigned Teacher",
    ]

    ws.append([])
    ws.append(headers)

    # Header styling
    for cell in ws[4]:
        cell.font = Font(
            bold=True,
            color="FFFFFF",
        )

        cell.fill = PatternFill(
            start_color="172033",
            end_color="172033",
            fill_type="solid",
        )

        cell.alignment = Alignment(
            horizontal="center",
        )

    # Student data
    for student in students:

        percentage = float(
            student.__dict__.get("attendance_percentage") or 0.0
        )

        standing = (
            "Good Standing" if percentage >= 85
            else "Needs Attention" if percentage >= 75
            else "Low Attendance"
        )

        teacher = db.query(models.User).filter(
            models.User.id == student.teacher_id
        ).first()

        ws.append([
            student.__dict__.get("id"),
            student.name,
            f"{percentage:.1f}%",
            standing,
            teacher.name if teacher else "N/A",
        ])

    # Column widths
    widths = [15, 25, 18, 22, 25]

    for index, width in enumerate(widths, start=1):
        column_letter = openpyxl.utils.get_column_letter(index)

        ws.column_dimensions[column_letter].width = width

    # Save workbook to memory
    stream = io.BytesIO()

    wb.save(stream)
    stream.seek(0)

    filename = f"attendance_report_{date.today()}.xlsx"

    return Response(
        content=stream.getvalue(),
        media_type=(
            "application/vnd.openxmlformats-officedocument."
            "spreadsheetml.sheet"
        ),
        headers={
            "Content-Disposition": f"attachment; filename={filename}"
        },
    )


# ==========================================
# EXPORT PDF
# ==========================================

@router.get("/reports/export/pdf")
def export_pdf(
    current_user=Depends(get_current_user),
    db: Session = Depends(get_db),
):

    students = get_report_students(current_user, db)

    stream = io.BytesIO()

    doc = SimpleDocTemplate(
        stream,
        pagesize=letter,
        rightMargin=30,
        leftMargin=30,
        topMargin=30,
        bottomMargin=30,
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontSize=17,
        textColor=colors.HexColor("#FF7A00"),
        spaceAfter=8,
    )

    # Explicitly declare Flowable list for Pyrefly
    story: list[Flowable] = [
        Paragraph(
            "XYZ AI Assistant - Attendance Report",
            title_style,
        ),
        Paragraph(
            f"Generated by {current_user.name} | "
            f"Date: {date.today()}",
            styles["Normal"],
        ),
        Spacer(1, 15),
    ]

    # Table headers
    data = [
        [
            "Student ID",
            "Student Name",
            "Attendance %",
            "Standing",
        ]
    ]

    # Student data
    for student in students:

        percentage = float(
            student.__dict__.get("attendance_percentage") or 0.0
        )

        standing = (
            "Good Standing" if percentage >= 85
            else "Needs Attention" if percentage >= 75
            else "Low Attendance"
        )

        data.append([
            f"#{student.__dict__.get('id')}",
            student.name,
            f"{percentage:.1f}%",
            standing,
        ])

    # Create PDF table
    table = Table(
        data,
        colWidths=[75, 200, 100, 150],
        repeatRows=1,
    )

    table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#172033")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            (
                "ROWBACKGROUNDS",
                (0, 1),
                (-1, -1),
                [colors.white, colors.HexColor("#F8FAFC")],
            ),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("PADDING", (0, 0), (-1, -1), 6),
        ])
    )

    # Append table as a Flowable
    story.append(table)

    # Build PDF
    doc.build(story)

    stream.seek(0)

    filename = f"attendance_report_{date.today()}.pdf"

    return Response(
        content=stream.getvalue(),
        media_type="application/pdf",
        headers={
            "Content-Disposition": f"attachment; filename={filename}"
        },
    )